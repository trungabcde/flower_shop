-- Does not modify any Lab 5 catalog/BOM tables.
BEGIN;
CREATE TABLE IF NOT EXISTS routing_departments (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL
);
CREATE TABLE IF NOT EXISTS routing_work_centers (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL, type_name text NOT NULL,
 department_id integer NOT NULL REFERENCES routing_departments(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS routing_operation_types (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL,
 parent_id integer REFERENCES routing_operation_types(id) ON DELETE RESTRICT,
 CONSTRAINT routing_optype_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE TABLE IF NOT EXISTS routing_professions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL,
 parent_id integer REFERENCES routing_professions(id) ON DELETE RESTRICT,
 base_hourly_rate numeric(14,4) NOT NULL CHECK (base_hourly_rate > 0),
 CONSTRAINT routing_prof_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE TABLE IF NOT EXISTS routing_qualifications (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL,
 coefficient numeric(10,4) NOT NULL CHECK (coefficient > 0),
 sort_order integer NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS routing_tools (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name text NOT NULL,
 kind varchar(15) NOT NULL CHECK(kind IN ('tool','fixture'))
);
CREATE TABLE IF NOT EXISTS routing_material_prices (
 product_id integer PRIMARY KEY REFERENCES products(id_product) ON DELETE RESTRICT,
 unit_cost numeric(14,4) NOT NULL CHECK(unit_cost>=0)
);
CREATE TABLE IF NOT EXISTS routing_routes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL,
 spec_version_id integer NOT NULL REFERENCES spec_versions(id_spec_version) ON DELETE RESTRICT,
 variant_id integer REFERENCES spec_variants(id_variant) ON DELETE RESTRICT,
 final_node_id integer
);
CREATE UNIQUE INDEX IF NOT EXISTS routing_route_only_version
 ON routing_routes(spec_version_id) WHERE variant_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS routing_route_version_variant
 ON routing_routes(spec_version_id,variant_id) WHERE variant_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS routing_typical_processes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, final_operation_id integer
);
CREATE TABLE IF NOT EXISTS routing_tp_parameters (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 process_id integer NOT NULL REFERENCES routing_typical_processes(id) ON DELETE RESTRICT,
 code varchar(80) NOT NULL, name text NOT NULL,
 default_value numeric(18,6) NOT NULL, min_value numeric(18,6), max_value numeric(18,6),
 integer_only boolean NOT NULL DEFAULT false,
 UNIQUE(process_id,code),
 CONSTRAINT routing_parameter_range CHECK(min_value IS NULL OR max_value IS NULL OR min_value<=max_value)
);
CREATE TABLE IF NOT EXISTS routing_tp_operations (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 process_id integer NOT NULL REFERENCES routing_typical_processes(id) ON DELETE RESTRICT,
 number integer NOT NULL, operation_name text NOT NULL, state_name text NOT NULL,
 description text,
 operation_type_id integer NOT NULL REFERENCES routing_operation_types(id) ON DELETE RESTRICT,
 work_center_id integer NOT NULL REFERENCES routing_work_centers(id) ON DELETE RESTRICT,
 profession_id integer NOT NULL REFERENCES routing_professions(id) ON DELETE RESTRICT,
 qualification_id integer NOT NULL REFERENCES routing_qualifications(id) ON DELETE RESTRICT,
 setup_minutes numeric(18,6) NOT NULL DEFAULT 0 CHECK(setup_minutes>=0),
 time_base numeric(18,6) NOT NULL DEFAULT 0,
 time_factor numeric(18,6) NOT NULL DEFAULT 0,
 time_parameter_id integer REFERENCES routing_tp_parameters(id) ON DELETE RESTRICT,
 UNIQUE(process_id,number)
);
CREATE TABLE IF NOT EXISTS routing_tp_inputs (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 output_operation_id integer NOT NULL REFERENCES routing_tp_operations(id) ON DELETE RESTRICT,
 input_operation_id integer REFERENCES routing_tp_operations(id) ON DELETE RESTRICT,
 input_product_id integer REFERENCES products(id_product) ON DELETE RESTRICT,
 quantity_base numeric(18,6) NOT NULL DEFAULT 0,
 quantity_factor numeric(18,6) NOT NULL DEFAULT 0,
 quantity_parameter_id integer REFERENCES routing_tp_parameters(id) ON DELETE RESTRICT,
 for_quantity numeric(18,6) NOT NULL DEFAULT 1 CHECK(for_quantity>0),
 CHECK ((input_operation_id IS NULL) <> (input_product_id IS NULL)),
 CHECK (input_operation_id IS NULL OR input_operation_id<>output_operation_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS routing_tp_input_unique_operation
 ON routing_tp_inputs(output_operation_id,input_operation_id)
 WHERE input_operation_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS routing_tp_input_unique_product
 ON routing_tp_inputs(output_operation_id,input_product_id)
 WHERE input_product_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS routing_tp_tools (
 operation_id integer NOT NULL REFERENCES routing_tp_operations(id) ON DELETE RESTRICT,
 tool_id integer NOT NULL REFERENCES routing_tools(id) ON DELETE RESTRICT,
 PRIMARY KEY(operation_id,tool_id)
);
CREATE TABLE IF NOT EXISTS routing_tp_applications (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_id integer NOT NULL REFERENCES routing_routes(id) ON DELETE RESTRICT,
 process_id integer NOT NULL REFERENCES routing_typical_processes(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS routing_tp_values (
 application_id integer NOT NULL REFERENCES routing_tp_applications(id) ON DELETE RESTRICT,
 parameter_id integer NOT NULL REFERENCES routing_tp_parameters(id) ON DELETE RESTRICT,
 value numeric(18,6) NOT NULL,
 PRIMARY KEY(application_id,parameter_id)
);
CREATE TABLE IF NOT EXISTS routing_nodes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind varchar(15) NOT NULL CHECK(kind IN ('purchase','production')),
 route_id integer REFERENCES routing_routes(id) ON DELETE RESTRICT,
 purchase_product_id integer REFERENCES products(id_product) ON DELETE RESTRICT,
 number integer, operation_name text, state_name text, description text,
 operation_type_id integer REFERENCES routing_operation_types(id) ON DELETE RESTRICT,
 work_center_id integer REFERENCES routing_work_centers(id) ON DELETE RESTRICT,
 profession_id integer REFERENCES routing_professions(id) ON DELETE RESTRICT,
 qualification_id integer REFERENCES routing_qualifications(id) ON DELETE RESTRICT,
 setup_minutes numeric(18,6) NOT NULL DEFAULT 0 CHECK(setup_minutes>=0),
 unit_minutes numeric(18,6) NOT NULL DEFAULT 0 CHECK(unit_minutes>=0),
 application_id integer REFERENCES routing_tp_applications(id) ON DELETE RESTRICT,
 template_operation_id integer REFERENCES routing_tp_operations(id) ON DELETE RESTRICT,
 CONSTRAINT routing_node_kind_check CHECK(
  (kind='purchase' AND purchase_product_id IS NOT NULL AND route_id IS NULL
    AND number IS NULL AND operation_name IS NULL AND state_name IS NULL
    AND operation_type_id IS NULL AND work_center_id IS NULL
    AND profession_id IS NULL AND qualification_id IS NULL
    AND description IS NULL AND setup_minutes=0 AND unit_minutes=0
    AND application_id IS NULL AND template_operation_id IS NULL)
  OR (kind='production' AND purchase_product_id IS NULL AND route_id IS NOT NULL
    AND number IS NOT NULL AND operation_name IS NOT NULL AND state_name IS NOT NULL
    AND operation_type_id IS NOT NULL AND work_center_id IS NOT NULL
    AND profession_id IS NOT NULL AND qualification_id IS NOT NULL)
 )
);
CREATE UNIQUE INDEX IF NOT EXISTS routing_unique_purchase ON routing_nodes(purchase_product_id)
 WHERE kind='purchase';
CREATE UNIQUE INDEX IF NOT EXISTS routing_unique_operation_number ON routing_nodes(route_id,number)
 WHERE kind='production';
CREATE TABLE IF NOT EXISTS routing_inputs (
 output_node_id integer NOT NULL REFERENCES routing_nodes(id) ON DELETE RESTRICT,
 input_node_id integer NOT NULL REFERENCES routing_nodes(id) ON DELETE RESTRICT,
 quantity numeric(18,6) NOT NULL CHECK(quantity>0),
 for_quantity numeric(18,6) NOT NULL CHECK(for_quantity>0),
 PRIMARY KEY(output_node_id,input_node_id),
 CHECK(output_node_id<>input_node_id)
);
CREATE TABLE IF NOT EXISTS routing_node_tools (
 node_id integer NOT NULL REFERENCES routing_nodes(id) ON DELETE RESTRICT,
 tool_id integer NOT NULL REFERENCES routing_tools(id) ON DELETE RESTRICT,
 PRIMARY KEY(node_id,tool_id)
);
CREATE TABLE IF NOT EXISTS routing_tp_application_outputs (
 application_id integer PRIMARY KEY REFERENCES routing_tp_applications(id) ON DELETE RESTRICT,
 node_id integer NOT NULL UNIQUE REFERENCES routing_nodes(id) ON DELETE RESTRICT
);
-- Add cyclic foreign keys last.
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='routing_route_final_fk') THEN
 ALTER TABLE routing_routes ADD CONSTRAINT routing_route_final_fk
 FOREIGN KEY(final_node_id) REFERENCES routing_nodes(id) ON DELETE RESTRICT;
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='routing_tp_final_fk') THEN
 ALTER TABLE routing_typical_processes ADD CONSTRAINT routing_tp_final_fk
 FOREIGN KEY(final_operation_id) REFERENCES routing_tp_operations(id) ON DELETE RESTRICT;
 END IF;
END $$;
COMMIT;
